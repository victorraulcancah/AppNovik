/// El módulo de un permiso (su primera parte).
String userPermissionModule(String permission) => permission.split('.').first;

/// El nombre con el que se muestra el módulo de un permiso.
String userPermissionModuleLabel(String permission) {
  final module = userPermissionModule(permission);
  return userPermissionModules[module] ??
      (module.isEmpty ? module : module[0].toUpperCase() + module.substring(1).replaceAll('-', ' '));
}
